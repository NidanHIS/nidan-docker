#!/usr/bin/env python3
"""Keycloak acceptance matrix: every acceptance criterion, the tests that prove it and how they did in the last run.

  python3 ac-matrix.py [reports/*.json ...] [--out KEYCLOAK-TEST-MATRIX.md]

Reads the Playwright JSON reports written by run-keycloak-suite.sh (default: the latest reports/run-*/), the criteria
(acceptance-criteria.json), recorded non-Playwright evidence (ac-evidence.yaml) and the specs' tags. Per criterion:
  PASSED   every executed test tagged with it passed (at least one ran)
  FAILED   at least one test tagged with it failed or timed out
  SKIPPED  tests exist and ran, but all were skipped (missing env or harness: see the test's skip reason)
  NOT RUN  tests exist in the specs, but no report has them (their stage was not run)
  EVIDENCE no Playwright test; covered by a recorded CI test, tool or document (ac-evidence.yaml)
  MANUAL   a [MAN] criterion: a person checks it (GO-LIVE-CHECKLIST)
  DEFERRED moved to a later phase by decision ("deferred" in acceptance-criteria.json)
  MISSING  nothing covers it
Exit 1 when anything is FAILED or MISSING.
"""
import json
import re
import sys
from collections import defaultdict
from pathlib import Path

import yaml

HERE = Path(__file__).resolve().parent
TAG = re.compile(r"@(KC-\d+-\d+)")


def walk(suite, file=""):
    file = suite.get("file") or file
    for spec in suite.get("specs", []):
        statuses = [r.get("status") for t in spec.get("tests", []) for r in t.get("results", [])[-1:]]
        if not statuses:
            statuses = ["skipped" if t.get("status") == "skipped" else "notrun" for t in spec.get("tests", [])]
        yield file, spec["title"], statuses
    for child in suite.get("suites", []):
        yield from walk(child, file)


def outcome(statuses):
    if any(s in ("failed", "timedOut", "interrupted") for s in statuses):
        return "FAILED"
    if any(s in ("passed", "flaky") for s in statuses):
        return "PASSED"
    return "SKIPPED"


def main(argv):
    out = HERE / "KEYCLOAK-TEST-MATRIX.md"
    if "--out" in argv:
        out = Path(argv[argv.index("--out") + 1])
        argv = [a for i, a in enumerate(argv) if a != "--out" and (i == 0 or argv[i - 1] != "--out")]
    reports = [Path(a) for a in argv[1:]]
    if not reports:
        runs = sorted((HERE / "reports").glob("run-*"))
        reports = sorted(runs[-1].glob("*.json")) if runs else []
    acs = json.loads((HERE / "acceptance-criteria.json").read_text())["acs"]
    evidence = yaml.safe_load((HERE / "ac-evidence.yaml").read_text()) or {}

    ran = defaultdict(list)          # AC -> [(file, title, outcome)]
    for rp in reports:
        data = json.loads(rp.read_text())
        for suite in data.get("suites", []):
            for file, title, statuses in walk(suite):
                for ac in set(TAG.findall(title)):
                    ran[ac].append((file, title, outcome(statuses), rp.stem))
    in_specs = set()
    for spec in (HERE / "specs").glob("*.spec.ts"):
        in_specs |= set(TAG.findall(spec.read_text()))

    rows, counts = [], defaultdict(int)
    for a in acs:
        i = a["id"]
        tests = ran.get(i, [])
        if tests:
            res = outcome([{"PASSED": "passed", "FAILED": "failed", "SKIPPED": "skipped"}[t[2]] for t in tests])
        elif i in in_specs:
            res = "NOT RUN"
        elif i in evidence:
            res = "EVIDENCE"
        elif a.get("deferred"):
            res = "DEFERRED"
        elif a["harness"] == "MAN":
            res = "MANUAL"
        else:
            res = "MISSING"
        counts[res] += 1
        names = "; ".join(sorted({f"{Path(t[0]).name} ({t[3]})" for t in tests}))
        if not tests and res == "EVIDENCE":
            names = "; ".join(e.get("test") or e.get("path") or e.get("note", "")[:60] for e in evidence[i] or [])
        rows.append((i, a["summary"].replace("|", "/"), res, names, "yes" if a["security"] else ""))

    lines = ["# Keycloak acceptance matrix", "",
             f"Generated by `ac-matrix.py` from {len(reports)} report(s): {', '.join(r.stem for r in reports) or 'none'}.", "",
             "| result | count |", "|---|---|"]
    for k in ("PASSED", "FAILED", "SKIPPED", "NOT RUN", "EVIDENCE", "MANUAL", "DEFERRED", "MISSING"):
        lines.append(f"| {k} | {counts[k]} |")
    story = None
    for i, summary, res, names, sec in rows:
        s = i.rsplit("-", 1)[0]
        if s != story:
            story = s
            lines += ["", f"## {s}", "", "| AC | security | result | criterion | covered by (stage) |", "|---|---|---|---|---|"]
        lines.append(f"| {i} | {sec} | {res} | {summary[:160]} | {names} |")
    out.write_text("\n".join(lines) + "\n")
    print(f"{len(acs)} criteria -> {out.name}: " + ", ".join(f"{k} {v}" for k, v in sorted(counts.items())))
    bad = [r[0] for r in rows if r[2] in ("FAILED", "MISSING")]
    if bad:
        print("FAILED or MISSING: " + ", ".join(bad))
    return 1 if bad else 0


if __name__ == "__main__":
    sys.exit(main(sys.argv))
