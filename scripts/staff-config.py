#!/usr/bin/env python3
"""Staff page jobs for this site (backlog KC-21-09, KC-20).

  KC_TOKEN_FILE=/secure/token scripts/staff-config.py [OUT_DIR] [--url http://127.0.0.1:8180/auth]
  (OUT_DIR default: proxy/staff-site, mounted read-only into the gateway)

Reads the job groups under /staff in realm "nidan" (admin API, the operator's own token from a file, never on the
command line) and writes
  staff-config.json   the jobs the Staff page offers: [{id, name, path}]
  staff-groups.map    the gateway's /staff-api allow entries for exactly these group ids: list members, add to /
                      remove from a job. Any other group id (an admin group, app-superusers) is 403 at the gateway,
                      before Keycloak's own permissions (KC-09) are even asked.
Only direct children of /staff with a /staff/<name> path and a UUID id are written. Re-run after adding a job,
then restart the gateway.
"""
import json
import os
import re
import sys
import urllib.error
import urllib.request
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
UUID = r"[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}"


def fetch(base, token, path, opener=urllib.request.urlopen):
    req = urllib.request.Request(f"{base.rstrip('/')}/admin/realms/nidan{path}",
                                 headers={"Authorization": f"Bearer {token}", "Accept": "application/json"})
    with opener(req, timeout=10) as resp:
        return json.loads(resp.read().decode())


def jobs_from(staff, children):
    """[(id, name, path)] for valid /staff/<name> children; (jobs, rejected) so nothing is silently dropped."""
    jobs, rejected = [], []
    if not re.fullmatch(UUID, str(staff.get("id", ""))) or staff.get("path") != "/staff":
        raise SystemExit("group /staff not found or has no valid id")
    for g in children:
        gid, name, path = str(g.get("id", "")), str(g.get("name", "")), str(g.get("path", ""))
        if re.fullmatch(UUID, gid) and re.fullmatch(r"[A-Za-z0-9 _-]{1,64}", name) and path == f"/staff/{name}":
            jobs.append((gid, name, path))
        else:
            rejected.append(path or name or gid)
    return sorted(jobs, key=lambda j: j[1].lower()), rejected


def render(jobs):
    config = {"_comment": "Generated by scripts/staff-config.py from realm nidan; re-run after adding a job.",
              "jobs": [{"id": i, "name": n, "path": p} for i, n, p in jobs]}
    lines = ["# Generated by scripts/staff-config.py: /staff-api group routes for this site's jobs only (KC-21-09)."]
    for gid, name, _ in jobs:
        lines += [f'"GET:/staff-api/groups/{gid}/members" /groups/{gid}/members;   # {name}',
                  f'"~^PUT:/staff-api/users/(?<u>{UUID})/groups/{gid}$" /users/$u/groups/{gid};',
                  f'"~^DELETE:/staff-api/users/(?<u>{UUID})/groups/{gid}$" /users/$u/groups/{gid};']
    return json.dumps(config, indent=2) + "\n", "\n".join(lines) + "\n"


def main(argv):
    args, base = list(argv[1:]), "http://127.0.0.1:8180/auth"
    if "--url" in args:
        i = args.index("--url")
        base = args[i + 1] if i + 1 < len(args) else ""
        del args[i:i + 2]
    if len(args) > 1 or not base:
        print(__doc__)
        return 2
    out = Path(args[0]) if args else ROOT / "proxy" / "staff-site"
    token_file = os.environ.get("KC_TOKEN_FILE", "")
    if not token_file or not Path(token_file).is_file():
        print("set KC_TOKEN_FILE to a file holding the operator's admin access token", file=sys.stderr)
        return 2
    token = Path(token_file).read_text().strip()
    try:
        staff = fetch(base, token, "/group-by-path/staff")
        children = fetch(base, token, f"/groups/{staff.get('id')}/children?first=0&max=200&briefRepresentation=true")
    except urllib.error.HTTPError as e:
        print(f"Keycloak answered {e.code} (token expired, not an admin, or no /staff group?)", file=sys.stderr)
        return 1
    jobs, rejected = jobs_from(staff, children)
    config, groups_map = render(jobs)
    out.mkdir(parents=True, exist_ok=True)
    (out / "staff-config.json").write_text(config, encoding="utf-8")
    (out / "staff-groups.map").write_text(groups_map, encoding="utf-8")
    for r in rejected:
        print(f"  skipped {r}: not a /staff/<name> group with a valid id")
    print(f"{len(jobs)} job(s) written to {out}: {', '.join(n for _, n, _ in jobs) or 'none'}")
    return 0 if jobs else 1


if __name__ == "__main__":
    sys.exit(main(sys.argv))
